const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('app', {
  ctx: () => ipcRenderer.invoke('ctx:get'),
  start: cfg => ipcRenderer.invoke('bot:start', cfg),
  stop: () => ipcRenderer.invoke('bot:stop'),
  kill: () => ipcRenderer.invoke('bot:kill'),
  detect: () => ipcRenderer.invoke('bot:detect'),
  reloadGame: () => ipcRenderer.invoke('game:reload'),
  setProfile: mode => ipcRenderer.invoke('game:profile', mode),
  creds: () => ipcRenderer.invoke('creds:get'),
  saveCreds: c => ipcRenderer.invoke('creds:save', c),
  clearCreds: () => ipcRenderer.invoke('creds:clear'),
  loginNow: () => ipcRenderer.invoke('login:now'),
  focusGame: () => ipcRenderer.invoke('game:focus'),
  presets: () => ipcRenderer.invoke('presets:list'),
  savePreset: p => ipcRenderer.invoke('presets:save', p),
  deletePreset: n => ipcRenderer.invoke('presets:delete', n),
  prefs: () => ipcRenderer.invoke('prefs:get'),
  savePrefs: p => ipcRenderer.invoke('prefs:save', p),
  accounts: () => ipcRenderer.invoke('accounts:get'),
  saveAccounts: list => ipcRenderer.invoke('accounts:save', list),
  shot: file => ipcRenderer.invoke('shot:get', file),
  snapshot: file => ipcRenderer.invoke('snap:get', file),
  instanceAction: (index, action) => ipcRenderer.invoke('instance:action', index, action),
  setGameViewVisible: v => ipcRenderer.invoke('ui:gameview', !!v),
  onEvent: fn => { const h = (_e, ev) => fn(ev); ipcRenderer.on('bot-event', h); return () => ipcRenderer.removeListener('bot-event', h); },
  onServerStatus: fn => { const h = (_e, st) => fn(st); ipcRenderer.on('server-status', h); return () => ipcRenderer.removeListener('server-status', h); },
});
